    @Test
    void shouldSupportNullableFields() {
        // Given: Items with different nullable fields
        // position setada explicitamente em cada item: a constraint
        // uq_list_items_list_position (V18) rejeita mais de um item com a
        // mesma position na mesma lista, e o default da entidade é 0.
        ListItem shoppingItem = new ListItem();
        shoppingItem.setName("Arroz");
        shoppingItem.setList(testList);
        shoppingItem.setCreatedBy(testUser);
        shoppingItem.setQuantity(5); // Compras: quantity
        shoppingItem.setPosition(0);
        listItemRepository.save(shoppingItem);

        ListItem taskItem = new ListItem();
        taskItem.setName("Fazer compras");
        taskItem.setList(testList);
        taskItem.setCreatedBy(testUser);
        taskItem.setDueDate(LocalDateTime.now().plusDays(1)); // Tarefas: dueDate
        taskItem.setPosition(1);
        listItemRepository.save(taskItem);

        ListItem wishlistItem = new ListItem();
        wishlistItem.setName("Cadeira Gamer");
        wishlistItem.setList(testList);
        wishlistItem.setCreatedBy(testUser);
        wishlistItem.setUrl("https://example.com/chair"); // Wishlist: url
        wishlistItem.setPosition(2);
        listItemRepository.save(wishlistItem);

        ListItem genericItem = new ListItem();
        genericItem.setName("Item genérico");
        genericItem.setList(testList);
        genericItem.setCreatedBy(testUser);
        // Genérica: sem campos especiais
        genericItem.setPosition(3);
        listItemRepository.save(genericItem);

        // When/Then: Verify all items saved correctly with nullable fields
        assertEquals(4, listItemRepository.count());

        ListItem savedShopping = listItemRepository.findById(shoppingItem.getId()).orElseThrow();
        assertEquals(5, savedShopping.getQuantity());
        assertNull(savedShopping.getDueDate());
        assertNull(savedShopping.getUrl());

        ListItem savedTask = listItemRepository.findById(taskItem.getId()).orElseThrow();
        assertNull(savedTask.getQuantity());
        assertNotNull(savedTask.getDueDate());
        assertNull(savedTask.getUrl());

        ListItem savedWishlist = listItemRepository.findById(wishlistItem.getId()).orElseThrow();
        assertNull(savedWishlist.getQuantity());
        assertNull(savedWishlist.getDueDate());
        assertEquals("https://example.com/chair", savedWishlist.getUrl());

        ListItem savedGeneric = listItemRepository.findById(genericItem.getId()).orElseThrow();
        assertNull(savedGeneric.getQuantity());
        assertNull(savedGeneric.getDueDate());
        assertNull(savedGeneric.getUrl());
    }

    @Test
    void shouldUpdateUpdatedAtOnModify() {
        // Given: Item created - @PrePersist sets timestamps
        ListItem item = new ListItem();
        item.setName("Original Name");
        item.setList(testList);
        item.setCreatedBy(testUser);
        ListItem saved = listItemRepository.saveAndFlush(item);
        LocalDateTime originalUpdatedAt = saved.getUpdatedAt();

        // When: Wait and modify
        try {
            Thread.sleep(100); // Ensure timestamp difference
        } catch (InterruptedException e) {
            // Ignore
        }
        saved.setName("Updated Name");
        ListItem updated = listItemRepository.saveAndFlush(saved);

        // Then: @PreUpdate must update updatedAt automatically
        assertTrue(updated.getUpdatedAt().isAfter(originalUpdatedAt),
            "@PreUpdate should auto-update updatedAt");
    }

