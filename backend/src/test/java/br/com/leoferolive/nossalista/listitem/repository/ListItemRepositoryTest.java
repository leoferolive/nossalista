    @Test
    void shouldEnforceForeignKeyConstraintOnList() {
        // Given: Create a transient List (not persisted, no ID)
        SharedList transientList = new SharedList();
        transientList.setName("Transient List");
        transientList.setTypeId(1);
        transientList.setOwner(testUser);
        // Not persisted - remains transient

        ListItem item = new ListItem();
        item.setName("Orphan Item");
        item.setCreatedBy(testUser);
        item.setList(transientList);

        // When/Then: Hibernate detects transient instance before flush
        // and throws InvalidDataAccessApiUsageException (wrapped TransientPropertyValueException)
        assertThrows(org.springframework.dao.InvalidDataAccessApiUsageException.class, () -> {
            listItemRepository.saveAndFlush(item);
        });
    }

