    @Test
    void shouldVerifyCascadeDeleteIsConfiguredInMigration() {
        // This test verifies CASCADE DELETE at database level using native SQL
        // JPA-level cascade testing requires complex transaction management and
        // can be brittle. Instead, we verify the database constraint directly.

        // Given: Item with valid list and creator
        ListItem item = new ListItem();
        item.setName("Cascade Test Item");
        item.setList(testList);
        item.setCreatedBy(testUser);
        ListItem saved = listItemRepository.saveAndFlush(item);
        UUID itemId = saved.getId();
        UUID listId = testList.getId();

        // Verify item exists
        assertTrue(listItemRepository.existsById(itemId));
        assertEquals(1, listItemRepository.countByListId(listId));

        // When: Delete list using native SQL (bypasses JPA cascade complexity)
        entityManager.createNativeQuery("DELETE FROM lists WHERE id = :listId")
            .setParameter("listId", listId)
            .executeUpdate();

        // Clear JPA cache to force fresh queries
        entityManager.flush();
        entityManager.clear();

        // Then: Item must be automatically deleted by database CASCADE constraint
        assertFalse(listItemRepository.existsById(itemId),
            "CASCADE DELETE: Item should be deleted when list is deleted");
        assertEquals(0, listItemRepository.countByListId(listId),
            "No items should remain after list CASCADE deletion");

        // The CASCADE DELETE is configured at database level in V4__create_list_items.sql:
        // CONSTRAINT fk_list_items_list FOREIGN KEY (list_id) REFERENCES lists(id) ON DELETE CASCADE
    }

